import numpy as np
import matplotlib.pyplot as plt
import os

# Parameters as defined in calculate_sorting.py
Ls = [8, 10, 12, 14, 16, 18]
gi = 1.5
gf = 0.5
angle = 0.0
t_start = 0.0
dt = 0.01
Ndt = 100
ts = [10, 20, 30, 40, 50, 60, 70, 80, 90]
#ncs=[2,4,6,8,10,20,50]
ncs=[0.5,1.0,1.5]
# Calculate the physical time step t
fsize=18

# Reconstruct the file path used in calculate_sorting.py
output_dir = "wavefunctions_data"
two_sortings = [True]

# Formatting the plots
for t_idx in ts:
    t = t_start + t_idx * dt

    plt.figure(figsize=(8, 5))
    plt.title(f'infidelity vs system size | $g_i$={gi}, $g_f$={gf}, angle={angle}, t={t:.2f}')
    plt.yscale('log')
    plt.xscale('log')
    plt.ylabel(r"$I_{nc}(L)$",fontsize=fsize)
    plt.xlabel("System size $(L)$",fontsize=fsize)
    infs = np.zeros((len(two_sortings),len(Ls),len(ncs)))
    for idx_sort,sort in enumerate(two_sortings):
        for idx_L,L in enumerate(Ls):
            
            base_name_inf = f"inf_L{L}gi{gi:.2f}gf{gf:.2f}ti{t_start}dt{dt}t{t_idx}Nt{Ndt}C{sort}.npy"
            filename_inf = os.path.join(output_dir, base_name_inf)
            if not os.path.exists(filename_inf):
                raise FileNotFoundError(f"Cannot find the data file: {filename_inf}. Ensure calculate_sorting.py has been run.")


            # Load the data generated by calculate_sorting.py
            inf_data = np.load(filename_inf)
            for idx_nc,nc in enumerate(ncs):
                try:
                    nn=int(nc*L)
                    infs[idx_sort,idx_L,idx_nc] =inf_data[nn]
                except:
                    print("short range")
        for idx_nc,nc in enumerate(ncs):
            plt.plot(Ls,infs[idx_sort,:,idx_nc],marker="o",linestyle="dashed",label=r"$n_c="+str(ncs[idx_nc])+"$")
    
    # Save the figure to the same directory as the data
    plot_filename = os.path.join(output_dir, f"plot_L_norm_inf_dependence_gi{gi:.2f}gf{gf:.2f}t{t_idx}.png")
    plt.legend(fontsize=15)
    plt.savefig(plot_filename, dpi=300, bbox_inches='tight')
    print(f"Plot saved successfully to: {plot_filename}")

    # Display the plot
    plt.show()
