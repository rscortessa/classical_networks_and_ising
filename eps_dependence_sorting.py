import numpy as np
import matplotlib.pyplot as plt
import os

# Parameters as defined in calculate_sorting.py
Ls = [8, 10, 12, 14, 16, 18, 20]
gi = 1.5
gf = 0.5
angle = 0.0
t_start = 0.0
dt = 0.01
Ndt = 100
t_idx = 70
eps=[1e-2,1e-3,1e-4]
#ncs=[2,4,6,8,10,20,50]
# Calculate the physical time step t
fsize=18

# Reconstruct the file path used in calculate_sorting.py
output_dir = "wavefunctions_data"
two_sortings = [True]

# Formatting the plots
infs = np.zeros((len(two_sortings),len(eps),len(Ls)))


for idx,eps_idx in enumerate(eps):
    t = t_start + t_idx * dt

    
    for idx_sort,sort in enumerate(two_sortings):
        for idx_L,L in enumerate(Ls):
            
            base_name_inf = f"inf_L{L}gi{gi:.2f}gf{gf:.2f}ti{t_start}dt{dt}t{t_idx}Nt{Ndt}C{sort}.npy"
            filename_inf = os.path.join(output_dir, base_name_inf)
            if not os.path.exists(filename_inf):
                raise FileNotFoundError(f"Cannot find the data file: {filename_inf}. Ensure calculate_sorting.py has been run.")


            # Load the data generated by calculate_sorting.py
            inf_data = np.load(filename_inf)
            num_parameters = np.arange(len(inf_data))

            mask = inf_data>eps_idx
            y_left = inf_data[mask][-1]
            left_bound = num_parameters[mask][-1]

            mask = inf_data<eps_idx
            right_bound = num_parameters[mask][0]
            y_right = inf_data[mask][0]

            m = (np.log(y_right)-np.log(y_left))/(right_bound-left_bound)
            nc = (np.log(eps_idx)-np.log(y_right))/m+right_bound
            
            infs[idx_sort,idx,idx_L] =nc



import matplotlib.cm as cm
import matplotlib.colors as mcolors
import os
# (Make sure plt is imported as well)

plt.figure(figsize=(8, 5))
plt.title(rf'$n_c \;vs\; L \;|\; g_i={gi},\; g_f={gf},\; t={np.round(t_idx*0.01,2)},\theta={angle}$')
plt.yscale('log')
plt.xscale("log")
plt.ylabel(r"$n_{c}(L)$", fontsize=fsize)
plt.xlabel(r"$L$", fontsize=fsize)

# 1. Set up the colormap and normalization based on your 't' values
cmap = plt.get_cmap('viridis') # 'plasma', 'inferno', or 'coolwarm' also work well
norm = mcolors.LogNorm(vmin=min(eps), vmax=max(eps))

# 2. Set up different styles for your two sortings so they are distinguishable
linestyles = ['-', '--']
markers = ['o', 's']

for idx_sort, sort in enumerate(two_sortings):
    for idx_t, eps_idx in enumerate(eps):
        
        # Get the specific color for this t value
        color = cmap(norm(eps_idx))
        
        # Only add a label during the first sorting loop to prevent duplicate legend entries
        lbl = str(round(eps_idx, 4)) if idx_sort == 0 else None
        
        plt.plot(Ls, infs[idx_sort, idx_t, :], 
                 marker=markers[idx_sort % len(markers)], 
                 linestyle=linestyles[idx_sort % len(linestyles)], 
                 color=color, 
                 label=lbl)

# Save the figure 
plot_filename = os.path.join(output_dir, f"plot_t_099_dependence_gi{gi:.2f}gf{gf:.2f}epsss.png")

# Optional: Move legend outside the plot if you have many 't' values
plt.legend(title=r"$\epsilon$", fontsize=15, bbox_to_anchor=(1.05, 1), loc='upper left')

plt.savefig(plot_filename, dpi=300, bbox_inches='tight')
print(f"Plot saved successfully to: {plot_filename}")

# Display the plot
plt.show()
